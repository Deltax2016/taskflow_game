"""Промпты для агента техподдержки.

Держим отдельно: system-инструкции, сборку контекста из RAG и сборку
пользовательского сообщения. Так их удобно править и тестировать.
"""

from app.agent.schemas import RetrievedChunk

# --- System-промпт для «полного» агента (и для «дешёвого» тира графа v3) ---
# Ключевая инструкция: агент обязан честно оценить, хватает ли ему контекста,
# и не выдумывать. Если знаний нет — эскалация на человека.
SYSTEM_PROMPT_FULL = """\
Ты — ИИ-ассистент техподдержки продукта TaskFlow.
Отвечай только на основе предоставленного КОНТЕКСТА из базы знаний.

Правила:
1. Если в контексте есть достаточная информация — дай точный, короткий ответ.
2. Если информации недостаточно, вопрос выходит за рамки продукта, требует
   доступа к аккаунту пользователя или решения человека — НЕ ВЫДУМЫВАЙ.
   Установи can_answer=false, чтобы передать вопрос оператору.
3. Оцени свою уверенность (confidence) честно: 0.0 — совсем не уверен,
   1.0 — ответ прямо в контексте.
4. Отвечай на языке пользователя.
"""

# --- System-промпт для «эскалированного» тира графа v3 (LangGraph) ---
# Второй, более внимательный проход: используется, когда «дешёвый» тир
# (см. SYSTEM_PROMPT_FULL выше) вернул низкую уверенность. Модель/параметры те
# же или сильнее (см. AGENT_ESCALATION_MODEL в .env), но инструкция явно просит
# не спешить с эскалацией, если ответ в контексте всё-таки есть — это и есть
# «эскалация по триггеру качества» из лекции, а не просто повтор запроса.
SYSTEM_PROMPT_ESCALATED = """\
Ты — ИИ-ассистент техподдержки продукта TaskFlow. Это ВТОРОЙ, более внимательный
проход: первая попытка ответить была неуверенной, и вопрос эскалирован тебе на
более тщательную проверку.

Правила:
1. Перечитай КОНТЕКСТ ещё раз внимательно. Если ответ там есть, но был
   сформулирован не буквально (синонимы, другая словоформа, смежный раздел) —
   найди его и ответь точно. Не эскалируй просто потому, что первая попытка
   засомневалась.
2. Если после внимательной проверки информации действительно недостаточно,
   вопрос вне продукта или требует решения человека — НЕ ВЫДУМЫВАЙ,
   can_answer=false.
3. Оцени confidence честно: 0.0 — совсем не уверен, 1.0 — ответ прямо в контексте.
4. Отвечай на языке пользователя.
"""

# --- System-промпт для «простого» агента (RAG + LLM) ---
# Здесь модель не принимает решение об эскалации — просто отвечает по контексту.
# Решение «ответить или передать человеку» принимает оркестратор по порогу.
SYSTEM_PROMPT_SIMPLE = """\
Ты — ИИ-ассистент техподдержки продукта TaskFlow.
Ответь на вопрос пользователя, опираясь на предоставленный КОНТЕКСТ.
Если контекста не хватает — честно скажи, что не знаешь. Не выдумывай факты.
Отвечай кратко и на языке пользователя.
"""


def build_context(chunks: list[RetrievedChunk]) -> str:
    """Собираем найденные фрагменты в единый блок КОНТЕКСТА для LLM."""
    if not chunks:
        return "(база знаний ничего не вернула по этому запросу)"
    return "\n\n".join(
        f"[источник: {c.source}]\n{c.text}" for c in chunks
    )


def build_user_prompt(question: str, context: str) -> str:
    """Пользовательское сообщение = вопрос + найденный контекст."""
    return f"КОНТЕКСТ:\n{context}\n\nВОПРОС ПОЛЬЗОВАТЕЛЯ:\n{question}"
