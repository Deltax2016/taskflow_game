"""Классификация сетевых ошибок: что стоит повторить, а что — нет.

Общий кусок для ДВУХ мест, которые ходят по сети и должны решать, ретраить
ли сбой: узлы графа (`agent/graph/nodes.py`, вызовы LLM) и инструменты
(`agent/tools/`, вызовы внешних API). Вынесено сюда, чтобы не дублировать
одну и ту же логику в двух модулях.

Прямой вывод из реального инцидента (см. lesson-plan v3): 400 Bad Request
из-за отсутствия слова "json" в промпте — это БАГ, повтор его не лечит,
только жжёт бюджет и время. А вот таймаут, 429 (rate limit) и 5xx у
провайдера — временные сбои, которые почти наверняка пройдут со второй
попытки. Одна и та же логика применима что к LLM-провайдеру, что к любому
внешнему API инструмента — граница «баг vs временный сбой» не зависит от
того, кого вызвали.
"""

import httpx


def is_transient_http_error(exc: BaseException) -> bool:
    if isinstance(exc, httpx.TimeoutException):
        return True
    if isinstance(exc, httpx.HTTPStatusError):
        return exc.response.status_code in (429, 500, 502, 503, 504)
    return False
